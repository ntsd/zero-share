import { strict as assert } from 'node:assert';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

// Regression guard for the RSA-OAEP modulus (P0: it was silently reverted to 1024
// in PR #29's net diff). Pinned so any future revert of the constant fails CI.
const here = dirname(fileURLToPath(import.meta.url));
const source = readFileSync(join(here, '..', 'src', 'utils', 'crypto.ts'), 'utf8');

const modulusMatch = source.match(/modulusLength:\s*(\d+)/);
assert.ok(modulusMatch, 'src/utils/crypto.ts must define an RSA modulusLength');
assert.equal(Number(modulusMatch[1]), 2048, 'RSA-OAEP modulusLength must be 2048 bits');

// End-to-end sanity: the key pair generated by the module really is 2048-bit.
// Node strips the type annotations in crypto.ts natively (erasable TS syntax).
const {
  generateRsaKeyPair,
  generateAesKey,
  encryptAesKeyWithRsaPublicKey,
  decryptAesKeyWithRsaPrivateKey
} = await import(join(here, '..', 'src', 'utils', 'crypto.ts'));
const keyPair = await generateRsaKeyPair();
const jwk = await crypto.subtle.exportKey('jwk', keyPair.publicKey);
// 2048-bit modulus = 256 bytes; base64url without padding = 4 * ceil(256 / 3) - 2 = 342
assert.equal(jwk.n.length, 342, 'generated RSA public key modulus must be 2048 bits');

// OAEP digest pin regression (P0): the encrypt/decrypt option objects used to
// drop the `hash` field, so the padding digest silently fell back to the
// implementation default instead of the declared SHA-256 keygen hash.
// Statically assert no bare-name RSA-OAEP option object survives in the module:
assert.ok(
  !/\{\s*name:\s*rsaGenParams\.name\s*\}/.test(source),
  'encrypt/decrypt must not build the RSA-OAEP options with only name from rsaGenParams'
);
assert.ok(
  !/\{\s*name:\s*'RSA-OAEP'\s*\}/.test(source),
  'encrypt/decrypt must not use a bare { name: "RSA-OAEP" } option object without a hash'
);
assert.ok(
  (source.match(/hash:\s*rsaGenParams\.hash/g) ?? []).length >= 2,
  'both the RSA-OAEP encrypt and decrypt call sites must pin hash: rsaGenParams.hash'
);

// Dynamic round-trip: a random AES-256 key encrypted then decrypted through the
// module comes back byte-identical, proving both sides agree on the digest.
const aesKey = await generateAesKey();
const encryptedAesKey = await encryptAesKeyWithRsaPublicKey(keyPair.publicKey, aesKey);
const decryptedAesKey = await decryptAesKeyWithRsaPrivateKey(keyPair.privateKey, encryptedAesKey);
const originalRaw = await crypto.subtle.exportKey('raw', aesKey);
const decryptedRaw = await crypto.subtle.exportKey('raw', decryptedAesKey);
assert.ok(
  Buffer.from(originalRaw).equals(Buffer.from(decryptedRaw)),
  'RSA-OAEP round-trip of the AES key must preserve the key material'
);

// NOTE: the task's optional "ciphertext must reject a different digest" check
// is not implementable on Node's WebCrypto: it ignores the OAEP `hash` option
// on decrypt (verified empirically on Node 26 — every digest succeeds on the
// same ciphertext), so a negative test there would always pass vacuously.
// Instead, cross-check that the digest pinned at the call sites is the very one
// declared by the keygen params — the actual load-bearing invariant:
const declaredHashMatch = source.match(/const rsaGenParams[^;]*hash:\s*'([^']+)'/);
assert.ok(declaredHashMatch, 'rsaGenParams must declare a hash');
assert.equal(declaredHashMatch[1], 'SHA-256', 'rsaGenParams must declare hash: SHA-256');
assert.ok(
  source.includes(`hash: rsaGenParams.hash`),
  'call sites must pin the digest from rsaGenParams (no hard-coded digest string)'
);

console.log(
  'ok - RSA-OAEP modulus is 2048 bits (constant + generated key); OAEP digest pinned to SHA-256 on both encrypt and decrypt (static + round-trip)'
);
